/* ------------------------------------------------------------------
   Final chapter

   The PRD's closing text, near-verbatim, and its single button.

   An earlier draft of this project offered three doors — yes, slowly,
   not now — on the reasoning that one warm button makes "no" feel like
   breaking something. That reasoning is answered by the copy itself:
   "I'm not asking for an answer today" removes the pressure more
   cleanly than a menu of exits would, and a menu turns a letter into
   a form. One button, and the text does the work.

   Hard rules if you rewrite this:
   — No question is asked. Nothing here requires a reply.
   — Nothing is left open that she has to close.
   — No guilt, no "I'll wait forever" (that is a debt, not a gift).
------------------------------------------------------------------ */

